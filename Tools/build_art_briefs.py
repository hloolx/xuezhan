"""Build local Tripo design briefs; no image generation, network or game edits.

The curated catalog is checked against current game data on every run. Output
files belong only to RawAssets/Art/Tripo_v01.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / "RawAssets" / "Art" / "Tripo_v01"

STYLE = """Use case: stylized-concept
Project: CivWar, an original side-view civilization-evolution strategy game.
Art direction: substantial stylized forms, restrained detail, strong readable
silhouettes. Crafted broad planes and soft bevels, not primitive block figures.
All humans share 5.5-head proportions, slightly oversized hands and boots.
Matte fur, leather, cloth and stone; broad painted metal surfaces. No micro-noise.
Earthy umber, warm ivory, stone grey, cool steel, olive and graphite materials.
Controlled muted cobalt panels indicate replaceable faction-color areas, with
neutral materials dominant. No text or emblems. These are preview colors, not
an instruction to bake faction colors permanently into final textures.
Soft even studio illumination, no dramatic directional shadow or glossy plastic.
No bloom, smoke, fire, motion blur, painted lighting, depth of field or background scene.
"""

TURNAROUND = """Create one clean horizontal three-view review sheet with three equally wide
panels and generous empty gutters, arranged FRONT / SUBJECT'S RIGHT / BACK.
Do not print those labels. Each panel depicts the SAME object from a different
view, with identical design, pose, materials, scale and part counts. Orthographic
horizontal cameras, no perspective convergence. Same pixels per unit and ground
baseline. The narrower side silhouette must retain empty margin, not be enlarged.
Pure off-white background, full object uncropped, no stand or presentation plinth.
No diagram arrows, dimensions, labels, extra objects, alternate designs or inset views.
Important: this sheet is for REVIEW. Export each accepted single-object view to
a separate file for Tripo. Do not submit the complete sheet as a single-image job.
"""

HUMAN_POSE = """Production target: one unarmed human body with its attached clothing/armor only.
Use one neutral symmetrical A pose, arms 35-45 degrees away from torso, feet
naturally separated and flat, relaxed hands clear of hips. Keep pose identical
across all views. No handheld weapon, shield, mount, loose props or base.
Do not fuse arms to torso, hands to clothes, or legs to each other.
Give each hand a distinct thumb opposed to four readable fingers, with clear
web spaces; no mitten blobs. Keep neutral fingers gently separated, not a frozen
closed fist. Final finger articulation and grip poses require DCC rig validation.
Reserve shoulder, elbow, wrist, hip and knee clearance. Armor plates must not
bridge bending joints. Short hems must allow walking and seated rider poses.
"""

MOUNT_POSE = """Production target: one quadruped only, no rider or weapon. Four feet on the
same ground, calm neutral standing pose, identical in every view. Exactly four
legs. Preserve natural occlusion in strict side view; do not change leg pose to
fake visibility. If necessary add a separate fourth view for inspection.
"""

MECHANICAL = """Production target: one complete mechanical exterior, shown consistently at rest.
Visible seams define moving components. No exploded layout or loose parts around
the object. Image-to-3D does not guarantee separate functional parts: after generation
separate/rebuild each listed component and place exact pivots in DCC software.
"""

BASE = """Production target: one complete base exterior without installed defensive weapons,
people or effects. Exactly three clear horizontal turret attachment areas and an
open central forward gateway. Use broad structural forms, not a crowded diorama.
The thin foundation is part of the building; do not add a display pedestal.
Confirm dimensions, gate clearance and sockets in DCC; pictures are not CAD.
"""

SIMPLE = """Production target: one standalone asset only, complete and uncropped, no hand,
owner, display stand or neighboring objects. For simple shapes the three-view
sheet is a design reference; use DCC geometry instead of a paid 3D generation
where the catalog recommends it. Preserve front-to-back thickness and design.
"""

ENVIRONMENT = """Production target: one reusable environment module generated by Tripo.
Complete and uncropped, no display stand, neighboring objects or painted ground.
Preserve real front-to-back thickness. Broad readable forms; clustered foliage,
not thousands of tiny leaves. Blender is for inspecting and cleaning the actual
Tripo output, setting scale/origin and exporting, not replacing it with primitives.
"""


def read(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def dump(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def animation_spec(profile, src):
    spec = dict(profile)
    row = src["data"]
    interval = row["AttackInterval"]
    if interval <= 0:
        raise ValueError(f"Invalid attack interval: {row['VisualKey']}")
    spec["status"] = "design_only_not_implemented_or_rig_validated"
    if src["group"] == "unit":
        windup = row["AttackWindup"]
        if not 0 <= windup < interval:
            raise ValueError(f"Review animation timing: {row['VisualKey']}")
        spec["timing"] = {
            "clock": "nominal server attack start; simulation step and replication latency require synchronization",
            "cycle_seconds": interval,
            "release_seconds": windup,
            "recovery_budget_seconds": round(interval - windup, 4),
            "release_kind": "projectile" if row["ProjectileSpeed"] > 0 else "melee_contact",
            "charge_multiplier": row["ChargeMultiplier"],
            "client_notify_causes_damage": False,
        }
    else:
        spec["timing"] = {
            "clock": "FireSeq is already-fired event; no turret windup field exists",
            "cycle_seconds": interval,
            "release_seconds": 0,
            "recovery_budget_seconds": interval,
            "release_kind": "projectile" if row["ProjectileSpeed"] > 0 else "direct_damage",
            "client_notify_causes_damage": False,
        }
    return spec


def timing_text(spec):
    t = spec["timing"]
    if t["clock"].startswith("FireSeq"):
        return f"FireSeq 即发射；间隔 {t['cycle_seconds']:g}s；当前无炮塔前摇。"
    return (f"起手后 {t['release_seconds']:g}s 接触/释放；起手间隔 {t['cycle_seconds']:g}s；"
            f"收招预算 {t['recovery_budget_seconds']:g}s（需对齐服务器相位）。")


def integration_text(asset_id, name, own, usages, common):
    lines = [f"# {asset_id} · {name} · 武器与动作接入卡", "",
             "状态：设计契约，尚未完成模型绑定、动画实现或 UE 动态验收。", "",
             "[完整规范](../../../../../Docs/ART_WEAPONS_ANIMATION.md)", ""]
    if own:
        lines += [f"骨架/机构族：`{own['family']}`。", "",
                  f"持械/装配：{own['grip']}", "",
                  f"动作：{own['motion']}", "",
                  f"时序：{timing_text(own)}", "",
                  f"净空与风险：{own['clearance']}", "",
                  "拟建定位点（当前运行时未提供整套接口）：" + "、".join(own["anchors"]) + "。", "",
                  "基础动作：待机、移动（可移动资产）、攻击、受击、死亡/损毁。",
                  "附加动作：" + ("、".join(own["extra_clips"]) or "无独立附加片段要求") + "。", ""]
        if own.get("variant_requirement"):
            lines += ["状态同步要求：" + own["variant_requirement"], ""]
    for usage in usages:
        lines += [f"用于 `{usage['asset_id']}`：{usage['grip']}", "",
                  f"使用时的净空：{usage['clearance']}", "",
                  "需配合的装配定位点：" + "、".join(usage["anchors"]) + "。", ""]
    lines += ["## 共用约束", ""]
    lines += ["- " + value for value in common.values()]
    return "\n".join(lines) + "\n"


def main():
    catalog = read(PACK / "catalog.json")
    pipeline = read(PACK / "pipeline.json")
    presets = read(PACK / "generation_presets.json")["presets"]
    contracts_path = PACK / "animation_contracts.json"
    contracts = read(contracts_path)
    profiles = contracts["profiles"]
    source = {}
    hashes = {}
    for filename, group in (("Units.json", "unit"), ("Ages.json", "base"), ("Turrets.json", "turret")):
        path = ROOT / "Content" / "Data" / filename
        hashes[filename] = hashlib.sha256(path.read_bytes()).hexdigest()
        for row in read(path):
            key = row["VisualKey"]
            if key in source:
                raise ValueError(f"Duplicate game VisualKey: {key}")
            source[key] = {"source_file": f"Content/Data/{filename}", "group": group, "data": row}

    expected = set(source)
    core = catalog["core"]
    actual = {item["id"] for item in core}
    if expected != actual:
        raise ValueError(f"Catalog mismatch: missing={sorted(expected-actual)}, stale={sorted(actual-expected)}")
    items = core + catalog["support"]
    ids = [item["id"] for item in items]
    if len(ids) != len(set(ids)):
        raise ValueError("Duplicate catalog ID")
    # Layout carriers also appear in the execution queue but have no Tripo brief.
    known_ids = set(ids) | {item["id"] for item in catalog.get("non_tripo", [])}
    stale_overrides = set(pipeline["asset_overrides"]) - known_ids
    if stale_overrides:
        raise ValueError(f"Stale pipeline overrides: {sorted(stale_overrides)}")
    production_routes = {}
    for item in items:
        route_id = pipeline["asset_overrides"].get(item["id"], pipeline["kind_routes"][item["kind"]])
        route = {"id": route_id, **pipeline["routes"][route_id]}
        if route["request_preset"] and route["request_preset"] not in presets:
            raise ValueError(f"Unknown request preset: {route['request_preset']}")
        production_routes[item["id"]] = route
    for item in core:
        missing = set(item.get("modules", [])) - set(ids)
        if missing:
            raise ValueError(f"Missing dependencies for {item['id']}: {sorted(missing)}")

    combat_ids = {key for key, src in source.items() if src["group"] in ("unit", "turret")}
    if combat_ids != set(profiles):
        raise ValueError(f"Animation coverage mismatch: missing={sorted(combat_ids-set(profiles))}, "
                         f"stale={sorted(set(profiles)-combat_ids)}")
    for key, profile in profiles.items():
        for field in ("family", "grip", "motion", "clearance", "anchors", "extra_clips"):
            if field not in profile:
                raise ValueError(f"Missing animation field {key}.{field}")
    specs = {key: animation_spec(profile, source[key]) for key, profile in profiles.items()}
    hashes["animation_contracts.json"] = hashlib.sha256(contracts_path.read_bytes()).hexdigest()
    hashes["catalog.json"] = hashlib.sha256((PACK / "catalog.json").read_bytes()).hexdigest()
    for name in ("pipeline.json", "generation_presets.json"):
        hashes[name] = hashlib.sha256((PACK / name).read_bytes()).hexdigest()
    consumers = {}
    for item in core:
        if item["id"] in specs:
            for module in item.get("modules", []):
                spec = specs[item["id"]]
                consumers.setdefault(module, []).append({"asset_id": item["id"],
                    **{key: spec[key] for key in ("grip", "clearance", "anchors")}})

    age_names = {row["Index"]: row["DisplayName"] for row in read(ROOT / "Content/Data/Ages.json")}
    outputs = []
    index = ["# Tripo v01 · 全资产设计卡索引", "",
             "状态：本索引是设计/提示词交付；`planned` 不代表图片或模型完成。",
             "样板及图像实际状态另见 `samples/STATUS.md`，若该文件尚不存在则没有已登记样板。", "",
             f"核心资产 {len(core)} 项，辅助资产 {len(catalog['support'])} 项；共 {len(items)} 项设计卡。",
             "辅助项包含可用 DCC 直接制作的简单配件和 1 个建议新增矿井，并非同数量的付费生成任务。", "",
             f"生产计划 {pipeline['plan_version']}（{pipeline['updated_date']}）：先场地 Tripo 母件，再石斧战斗样板与同类扩展；人体需要四个独立视图。",
             "[执行阶段与 Claude 分工](pipeline.json) · [几何先行请求预设](generation_presets.json)", "",
             "[美术生产方案](../../../Docs/ART_PRODUCTION_TRIPO.md) · [武器与动画规范](../../../Docs/ART_WEAPONS_ANIMATION.md) · [24 项动作与时序表](ANIMATION_INDEX.md)", "",
             "| ID | 名称 | 时代/类别 | 优先级/方法 | 卡片 |", "|---|---|---|---|---|"]
    motion_index = ["# 武器与攻击动作 · 全量索引", "",
                    "设计契约；数值每次从当前游戏数据读取。尚无绑定或 UE 动态验收结论。",
                    "单位以起手为时间零点；炮塔 FireSeq 是已发射事件，两者不能共用前摇解释。", "",
                    "[完整规范](../../../Docs/ART_WEAPONS_ANIMATION.md)", "",
                    "| 资产 | 持械/机构 | 当前时序 | 卡片 |", "|---|---|---|---|"]

    for item in items:
        asset_id = item["id"]
        src = source.get(asset_id)
        row = src["data"] if src else {}
        name = row.get("DisplayName", item.get("name", asset_id))
        age = row.get("Age", row.get("Index"))
        era = age_names.get(age, "通用/配件")
        folder = PACK / "prompts" / asset_id
        folder.mkdir(parents=True, exist_ok=True)
        route = production_routes[asset_id]
        brief = dict(item)
        brief.update({"display_name": name, "era": era, "status": "planned",
                      "source": src, "review_views": route["review_views"],
                      "production_route": route, "plan_version": pipeline["plan_version"],
                      "upload_images": "Separate single-object views after consistency review",
                      "gameplay_camera": "20 degree pitch; 1300 / 2300 / 3400 cm; both team views"})
        if item["kind"] in ("human", "rider"):
            brief["production_target"] = "unarmed A-pose body; equipment generated separately"
            brief["reference_pose"] = pipeline["reference_pose"]
        if "Shield" in str(item.get("modules", [])):
            brief["additional_review_view"] = "left"
        own = specs.get(asset_id)
        usages = consumers.get(asset_id, [])
        if own:
            brief["animation_contract"] = own
        if usages:
            brief["assembly_usage"] = usages
        if own or usages:
            brief["integration_constraints"] = contracts["common"]
            (folder / "integration.md").write_text(
                integration_text(asset_id, name, own, usages, contracts["common"]), encoding="utf-8")
        dump(folder / "brief.json", brief)

        design = STYLE + f"\nAsset: {asset_id} / {name}\nSubject: {item['subject']}\n"
        if item.get("equipment"):
            design += "Assembly design: " + item["equipment"] + "\n"
        if item["kind"] == "rider":
            design += "This equipped mounted sheet is for ASSEMBLY REVIEW ONLY, not a fused-model generation input.\n"
        elif item["kind"] == "human":
            design += "Equipped views are design reference only; the body-production sheet uses a separate unarmed A pose.\n"
        if "front" in item:
            design += f"Review focus (front): {item['front']}\nReview focus (right): {item['right']}\nReview focus (back): {item['back']}\n"
        if own:
            design += "\nEquipped assembly contract: " + own["grip"] + "\nClearance: " + own["clearance"] + "\n"
        design += "\n" + TURNAROUND + "\nSpecific risk: " + item["risk"] + "\n"
        (folder / "design.txt").write_text(design, encoding="utf-8")

        production = STYLE + f"\nAsset: {asset_id} / {name}\n"
        production += "Subject: " + item.get("production_override", item["subject"]) + "\n"
        kind = item["kind"]
        if kind in ("human", "rider"):
            production += HUMAN_POSE
        elif kind == "mount":
            production += MOUNT_POSE
        elif kind in ("vehicle", "mech", "turret"):
            production += MECHANICAL
        elif kind == "base":
            production += BASE
        elif kind == "environment" and route["id"] == "environment_h":
            production += ENVIRONMENT
        else:
            production += SIMPLE
        if kind in ("vehicle", "mech") and item.get("equipment"):
            production += "Fixed configuration: " + item["equipment"] + "\n"
        if item.get("split"):
            production += "DCC component/pivot plan (not labels in image): " + ", ".join(item["split"]) + "\n"
        if own:
            production += "\nFuture assembly clearance; do not add omitted handheld props to the body sheet: " + own["clearance"] + "\n"
        if usages:
            production += "\nSeparate-asset assembly requirements (do not depict its owner):\n"
            for usage in usages:
                production += usage["asset_id"] + ": " + usage["grip"] + " " + usage["clearance"] + "\n"
        if asset_id.startswith("Weapon_"):
            production += "\nWeapon fit and DCC requirements: " + contracts["common"]["weapon"] + "\n"
        production += "\n" + TURNAROUND + "\nSpecific risk: " + item["risk"] + "\n"
        if "left" in route["review_views"]:
            production += "\nAlso prepare a SEPARATE subject-left view from the same approved reference and identical pose/scale. Keep the main review sheet three panels. Do not mirror the right view.\n"
        production += "\nProduction workflow (metadata, do not draw text): " + route["label"] + "\n"
        production += "Acceptance before batch production: " + route["acceptance"] + "\n"
        production += "\nConsistency workflow: derive views from the SAME approved asset reference; do not independently redesign each angle. Reference images must be attached when executing this as an edit.\n"
        (folder / "production.txt").write_text(production, encoding="utf-8")

        if own:
            action = (STYLE + f"\nAsset: {asset_id} / {name}\nSubject: {item['subject']}\n"
                      + "Equipment: " + item.get("equipment", "") + "\n"
                      + "Create an ANIMATION REVIEW BOARD ONLY, using the approved body and equipment images as references. "
                      "Do not execute this prompt without those references. Three equal panels show the SAME equipped asset "
                      "from the SAME readable side camera: prepared pose, contact/release pose, recovery pose. "
                      "Preserve scale, anatomy, hand ownership and equipment design; full body in every panel. "
                      "Poses intentionally differ, so this board MUST NOT be used as multiview-to-model input or processed by the upload splitter. "
                      "For mounted units include the assembled rider and mount; for turrets include moving equipment/crew. "
                      "No labels, motion trails or baked VFX. Images do not prove rig feasibility.\n"
                      + "Grip: " + own["grip"] + "\nAction: " + own["motion"]
                      + "\nTiming: " + timing_text(own) + "\nClearance: " + own["clearance"] + "\n")
            (folder / "action-reference.txt").write_text(action, encoding="utf-8")
            motion_index.append(f"| {name} · `{asset_id}` | {own['grip']} | {timing_text(own)} | "
                                f"[接入](prompts/{asset_id}/integration.md) · [动作参考提示词](prompts/{asset_id}/action-reference.txt) |")

        outputs.append({"id": asset_id, "name": name, "era": era, "kind": kind,
                        "status": "planned", "priority": item.get("priority"),
                        "method": route["label"], "production_route": route["id"],
                        "request_preset": route["request_preset"],
                        "brief": f"prompts/{asset_id}/brief.json",
                        "modules": item.get("modules", [])})
        links = f"[设计](prompts/{asset_id}/design.txt) · [生产](prompts/{asset_id}/production.txt)"
        if own or usages:
            outputs[-1]["integration"] = f"prompts/{asset_id}/integration.md"
            links += f" · [握持/动作](prompts/{asset_id}/integration.md)"
        index.append(f"| {asset_id} | {name} | {era} / {kind} | {item.get('priority', '')} {route['label']} | {links} |")

    skill_path = ROOT / "Content/Data/Skills.json"
    hashes["Skills.json"] = hashlib.sha256(skill_path.read_bytes()).hexdigest()
    skill_routes = {
        "Skill_Meteor": "简单陨石实体+Niagara 尾迹/冲击，不烘入火焰",
        "Skill_ArrowRain": "复用箭网格+Niagara 定向落下",
        "Skill_Artillery": "复用炮弹+爆炸/烟尘分镜",
        "Skill_Airstrike": "落弹与方向反馈，飞机外形另作为可选需求",
        "Skill_OrbitalBeam": "预警→光束接地→冲击，材质/Niagara"
    }
    skills = read(skill_path)
    if {s["VisualKey"] for s in skills} != set(skill_routes):
        raise ValueError("Skill coverage mismatch; update skill_routes")
    index += ["", "## 技能及非 Tripo 内容", "", "| 内容 | 制作路线 |", "|---|---|"]
    for skill in skills:
        index.append(f"| {skill['VisualKey']} · {skill['DisplayName']} | {skill_routes[skill['VisualKey']]} |")
    for item in catalog["non_tripo"]:
        index.append(f"| {item['name']} | {item['route']} |")
    (PACK / "INDEX.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    (PACK / "ANIMATION_INDEX.md").write_text("\n".join(motion_index) + "\n", encoding="utf-8")
    dump(PACK / "manifest.json", {
        "version": catalog["version"], "design_date": catalog["date"],
        "plan_version": pipeline["plan_version"], "plan_updated_date": pipeline["updated_date"],
        "status_note": "Planning inventory. Actual sample status is tracked separately in samples/STATUS.md.",
        "source_sha256": hashes,
        "coverage": {"core": len(core), "support": len(catalog["support"]), "skill": len(skills), "animation_contracts": len(specs)},
        "assets": outputs,
        "skills": [{"id": s["VisualKey"], "name": s["DisplayName"], "route": skill_routes[s["VisualKey"]]} for s in skills],
        "non_tripo": catalog["non_tripo"]})
    print(json.dumps({"core": len(core), "support": len(catalog["support"]), "total_briefs": len(items),
                      "skills": len(skills), "animation_contracts": len(specs),
                      "coverage": "all current VisualKeys matched", "index": str(PACK / "INDEX.md")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
