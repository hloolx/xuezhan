# -*- coding: utf-8 -*-
"""
CivWar editor content setup (run inside Unreal Editor 5.8).

Creates the assets that cannot be authored as plain text:
  * /Game/Maps/Battlefield        - empty level; the battlefield is built by C++ at runtime
  * /Game/Art/M_CWStylized        - lit material: Color * VertexColor, Roughness, Metallic, Emissive
  * /Game/Art/M_CWWarning         - translucent unlit material for skill warning circles
  * /Game/Data/Tables/DT_*        - optional (--tables): DataTables imported from Content/Data/*.json for viewing in editor
  * /Game/Audio/SFX_*             - SoundWaves imported from RawAssets/Audio (generated by Tools/gen_sfx.py)

Usage (command line):
  UnrealEditor-Cmd.exe CivWar.uproject -run=pythonscript -script="<project>/Tools/setup_content.py" -unattended -nosplash
or in the editor: Tools > Execute Python Script.

The script is idempotent: existing assets are kept (pass --force to rebuild materials).
"""
import os
import sys

import unreal

FORCE = "--force" in sys.argv
PROJECT_DIR = unreal.Paths.convert_relative_path_to_full(unreal.Paths.project_dir())
asset_lib = unreal.EditorAssetLibrary
mat_lib = unreal.MaterialEditingLibrary
tools = unreal.AssetToolsHelpers.get_asset_tools()


def log(msg):
    unreal.log("[CivWarSetup] " + msg)


def ensure_dir(path):
    if not asset_lib.does_directory_exist(path):
        asset_lib.make_directory(path)


def create_level():
    path = "/Game/Maps/Battlefield"
    if asset_lib.does_asset_exist(path):
        log("level exists: " + path)
        return
    ensure_dir("/Game/Maps")
    level_editor = unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
    if not level_editor.new_level(path):
        raise RuntimeError("failed to create level " + path)
    level_editor.save_current_level()
    log("created level: " + path)


def scalar_param(mat, name, default, x, y):
    node = mat_lib.create_material_expression(mat, unreal.MaterialExpressionScalarParameter, x, y)
    node.set_editor_property("parameter_name", name)
    node.set_editor_property("default_value", default)
    return node


def vector_param(mat, name, default, x, y):
    node = mat_lib.create_material_expression(mat, unreal.MaterialExpressionVectorParameter, x, y)
    node.set_editor_property("parameter_name", name)
    node.set_editor_property("default_value", default)
    return node


def new_material(name, folder):
    path = folder + "/" + name
    if asset_lib.does_asset_exist(path):
        if not FORCE:
            log("material exists: " + path)
            return None
        asset_lib.delete_asset(path)
    ensure_dir(folder)
    return tools.create_asset(name, folder, unreal.Material, unreal.MaterialFactoryNew())


def create_stylized_material():
    mat = new_material("M_CWStylized", "/Game/Art")
    if mat is None:
        return
    color = vector_param(mat, "Color", unreal.LinearColor(1.0, 1.0, 1.0, 1.0), -800, -100)
    vcol = mat_lib.create_material_expression(mat, unreal.MaterialExpressionVertexColor, -800, 120)
    base = mat_lib.create_material_expression(mat, unreal.MaterialExpressionMultiply, -450, 0)
    mat_lib.connect_material_expressions(color, "", base, "A")
    mat_lib.connect_material_expressions(vcol, "", base, "B")
    mat_lib.connect_material_property(base, "", unreal.MaterialProperty.MP_BASE_COLOR)

    rough = scalar_param(mat, "Roughness", 0.7, -450, 200)
    mat_lib.connect_material_property(rough, "", unreal.MaterialProperty.MP_ROUGHNESS)
    metal = scalar_param(mat, "Metallic", 0.0, -450, 300)
    mat_lib.connect_material_property(metal, "", unreal.MaterialProperty.MP_METALLIC)

    emissive = scalar_param(mat, "Emissive", 0.0, -800, 400)
    emis_mul = mat_lib.create_material_expression(mat, unreal.MaterialExpressionMultiply, -450, 420)
    mat_lib.connect_material_expressions(color, "", emis_mul, "A")
    mat_lib.connect_material_expressions(emissive, "", emis_mul, "B")
    mat_lib.connect_material_property(emis_mul, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)

    mat_lib.recompile_material(mat)
    asset_lib.save_loaded_asset(mat)
    log("created material: /Game/Art/M_CWStylized")


def create_warning_material():
    mat = new_material("M_CWWarning", "/Game/Art")
    if mat is None:
        return
    mat.set_editor_property("blend_mode", unreal.BlendMode.BLEND_TRANSLUCENT)
    mat.set_editor_property("shading_model", unreal.MaterialShadingModel.MSM_UNLIT)
    color = vector_param(mat, "Color", unreal.LinearColor(1.0, 0.2, 0.1, 1.0), -600, 0)
    boost = mat_lib.create_material_expression(mat, unreal.MaterialExpressionMultiply, -300, 0)
    boost.set_editor_property("const_b", 2.0)
    mat_lib.connect_material_expressions(color, "", boost, "A")
    mat_lib.connect_material_property(boost, "", unreal.MaterialProperty.MP_EMISSIVE_COLOR)
    opacity = scalar_param(mat, "Opacity", 0.4, -300, 200)
    mat_lib.connect_material_property(opacity, "", unreal.MaterialProperty.MP_OPACITY)
    mat_lib.recompile_material(mat)
    asset_lib.save_loaded_asset(mat)
    log("created material: /Game/Art/M_CWWarning")


def import_data_tables():
    tables = {
        "Rules": "CWRulesRow",
        "DamageMatrix": "CWDamageMatrixRow",
        "Ages": "CWAgeRow",
        "Units": "CWUnitRow",
        "Turrets": "CWTurretRow",
        "Skills": "CWSkillRow",
    }
    ensure_dir("/Game/Data/Tables")
    tasks = []
    for name, struct_name in tables.items():
        row_struct = unreal.load_object(None, "/Script/CivWar." + struct_name)
        if row_struct is None:
            log("row struct not found (is the CivWar module compiled?): " + struct_name)
            continue
        task = unreal.AssetImportTask()
        task.set_editor_property("filename", os.path.join(PROJECT_DIR, "Content", "Data", name + ".json"))
        task.set_editor_property("destination_path", "/Game/Data/Tables")
        task.set_editor_property("destination_name", "DT_" + name)
        task.set_editor_property("replace_existing", True)
        task.set_editor_property("automated", True)
        task.set_editor_property("save", True)
        factory = unreal.CSVImportFactory()
        settings = factory.get_editor_property("automated_import_settings")
        settings.set_editor_property("import_type", unreal.CSVImportType.ECSV_DATA_TABLE)
        settings.set_editor_property("import_row_struct", row_struct)
        task.set_editor_property("factory", factory)
        tasks.append(task)
    if tasks:
        tools.import_asset_tasks(tasks)
        log("imported %d data tables into /Game/Data/Tables (runtime still reads Content/Data/*.json)" % len(tasks))


def import_audio():
    """Import RawAssets/Audio/SFX_*.wav (generated by Tools/gen_sfx.py) as /Game/Audio/SFX_* SoundWaves."""
    src_dir = os.path.join(PROJECT_DIR, "RawAssets", "Audio")
    if not os.path.isdir(src_dir):
        log("no RawAssets/Audio folder - run Tools/gen_sfx.py first; audio will be silent")
        return
    ensure_dir("/Game/Audio")
    tasks = []
    for file_name in sorted(os.listdir(src_dir)):
        if not file_name.lower().endswith(".wav"):
            continue
        name = os.path.splitext(file_name)[0]
        if asset_lib.does_asset_exist("/Game/Audio/" + name) and not FORCE:
            continue
        task = unreal.AssetImportTask()
        task.set_editor_property("filename", os.path.join(src_dir, file_name))
        task.set_editor_property("destination_path", "/Game/Audio")
        task.set_editor_property("destination_name", name)
        task.set_editor_property("replace_existing", True)
        task.set_editor_property("automated", True)
        task.set_editor_property("save", True)
        tasks.append(task)
    if tasks:
        tools.import_asset_tasks(tasks)
    log("audio assets ready (%d imported this run)" % len(tasks))


def main():
    log("project: " + PROJECT_DIR)
    create_stylized_material()
    create_warning_material()
    import_audio()
    create_level()
    # DataTable 资产只用于在编辑器中查看数值（游戏运行时直接读取 Content/Data/*.json）。
    # UE 5.8.3 的命令行模式下自动导入 JSON DataTable 会在引擎内部断言崩溃，因此改为可选：加 --tables 才执行。
    if "--tables" in sys.argv:
        import_data_tables()
    log("done")


main()
